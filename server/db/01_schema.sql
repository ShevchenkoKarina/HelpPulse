
-- HelpPulse: платформа для організації доставки донатів і гуманітарної допомоги, створення таблиць


DROP VIEW  IF EXISTS v_active_deliveries CASCADE;
DROP TABLE IF EXISTS feedback        CASCADE;
DROP TABLE IF EXISTS delivery        CASCADE;
DROP TABLE IF EXISTS kit_item        CASCADE;
DROP TABLE IF EXISTS aid_kit         CASCADE;
DROP TABLE IF EXISTS request_item    CASCADE;
DROP TABLE IF EXISTS help_request    CASCADE;
DROP TABLE IF EXISTS requester       CASCADE;
DROP TABLE IF EXISTS donation_item   CASCADE;
DROP TABLE IF EXISTS donation        CASCADE;
DROP TABLE IF EXISTS donor           CASCADE;
DROP TABLE IF EXISTS stock           CASCADE;
DROP TABLE IF EXISTS warehouse       CASCADE;
DROP TABLE IF EXISTS item            CASCADE;
DROP TABLE IF EXISTS item_category   CASCADE;
DROP TABLE IF EXISTS volunteer       CASCADE;
DROP TABLE IF EXISTS route           CASCADE;
DROP TABLE IF EXISTS delivery_status CASCADE;

-- 1. Довідник категорій товарів
CREATE TABLE item_category (
    category_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL UNIQUE
);

-- 2. Довідник товарів
CREATE TABLE item (
    item_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER      NOT NULL,
    item_name   VARCHAR(150) NOT NULL,
    unit        VARCHAR(20)  NOT NULL DEFAULT 'шт',
    CONSTRAINT fk_item_category FOREIGN KEY (category_id)
        REFERENCES item_category (category_id)
);

-- 3. Заявники (хто просить допомогу)
CREATE TABLE requester (
    requester_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_name VARCHAR(150) NOT NULL,
    requester_type VARCHAR(30)  NOT NULL,
    phone          VARCHAR(20),
    address        VARCHAR(250) NOT NULL,
    region         VARCHAR(100) NOT NULL,
    CONSTRAINT chk_requester_type
        CHECK (requester_type IN ('людина', 'лікарня', 'організація'))
);

-- 4. Заявки на допомогу
CREATE TABLE help_request (
    request_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id  INTEGER     NOT NULL,
    created_at    DATE        NOT NULL DEFAULT CURRENT_DATE,
    priority      VARCHAR(10) NOT NULL DEFAULT 'середній',
    request_state VARCHAR(20) NOT NULL DEFAULT 'нова',
    CONSTRAINT fk_request_requester FOREIGN KEY (requester_id)
        REFERENCES requester (requester_id),
    CONSTRAINT chk_request_priority
        CHECK (priority IN ('низький', 'середній', 'високий', 'критичний')),
    CONSTRAINT chk_request_state
        CHECK (request_state IN ('нова', 'в обробці', 'виконана', 'скасована'))
);

-- 5. Позиції заявки (M:N між help_request та item)
CREATE TABLE request_item (
    request_id      INTEGER NOT NULL,
    item_id         INTEGER NOT NULL,
    quantity_needed INTEGER NOT NULL,
    CONSTRAINT pk_request_item PRIMARY KEY (request_id, item_id),
    CONSTRAINT fk_ri_request FOREIGN KEY (request_id) REFERENCES help_request (request_id),
    CONSTRAINT fk_ri_item    FOREIGN KEY (item_id)    REFERENCES item (item_id),
    CONSTRAINT chk_ri_quantity CHECK (quantity_needed > 0)
);

-- 6. Донори
CREATE TABLE donor (
    donor_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_name VARCHAR(150) NOT NULL,
    donor_type VARCHAR(20)  NOT NULL,
    phone      VARCHAR(20),
    email      VARCHAR(100) UNIQUE,
    CONSTRAINT chk_donor_type
        CHECK (donor_type IN ('особа', 'компанія', 'фонд'))
);

-- 7. Склади
CREATE TABLE warehouse (
    warehouse_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_name VARCHAR(100) NOT NULL UNIQUE,
    address        VARCHAR(250) NOT NULL,
    phone          VARCHAR(20)
);

-- 8. Пожертви
CREATE TABLE donation (
    donation_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_id      INTEGER NOT NULL,
    warehouse_id  INTEGER NOT NULL,
    donation_date DATE    NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT fk_donation_donor     FOREIGN KEY (donor_id)     REFERENCES donor (donor_id),
    CONSTRAINT fk_donation_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouse (warehouse_id)
);

-- 9. Позиції пожертви (M:N між donation та item)
CREATE TABLE donation_item (
    donation_id INTEGER NOT NULL,
    item_id     INTEGER NOT NULL,
    quantity    INTEGER NOT NULL,
    CONSTRAINT pk_donation_item PRIMARY KEY (donation_id, item_id),
    CONSTRAINT fk_di_donation FOREIGN KEY (donation_id) REFERENCES donation (donation_id),
    CONSTRAINT fk_di_item     FOREIGN KEY (item_id)     REFERENCES item (item_id),
    CONSTRAINT chk_di_quantity CHECK (quantity > 0)
);

-- 10. Залишки на складах (M:N між warehouse та item)
CREATE TABLE stock (
    warehouse_id INTEGER NOT NULL,
    item_id      INTEGER NOT NULL,
    quantity     INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT pk_stock PRIMARY KEY (warehouse_id, item_id),
    CONSTRAINT fk_stock_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouse (warehouse_id),
    CONSTRAINT fk_stock_item      FOREIGN KEY (item_id)      REFERENCES item (item_id),
    CONSTRAINT chk_stock_quantity CHECK (quantity >= 0)
);

-- 11. Набори допомоги
CREATE TABLE aid_kit (
    kit_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id   INTEGER NOT NULL,
    warehouse_id INTEGER NOT NULL,
    created_at   DATE    NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT fk_kit_request   FOREIGN KEY (request_id)   REFERENCES help_request (request_id),
    CONSTRAINT fk_kit_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouse (warehouse_id)
);

-- 12. Склад набору (M:N між aid_kit та item)
CREATE TABLE kit_item (
    kit_id   INTEGER NOT NULL,
    item_id  INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    CONSTRAINT pk_kit_item PRIMARY KEY (kit_id, item_id),
    CONSTRAINT fk_ki_kit  FOREIGN KEY (kit_id)  REFERENCES aid_kit (kit_id),
    CONSTRAINT fk_ki_item FOREIGN KEY (item_id) REFERENCES item (item_id),
    CONSTRAINT chk_ki_quantity CHECK (quantity > 0)
);

-- 13. Волонтери
CREATE TABLE volunteer (
    volunteer_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    volunteer_name VARCHAR(150) NOT NULL,
    phone          VARCHAR(20)  NOT NULL UNIQUE,
    region         VARCHAR(100)
);

-- 14. Маршрути
CREATE TABLE route (
    route_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_point VARCHAR(200) NOT NULL,
    end_point   VARCHAR(200) NOT NULL,
    distance_km NUMERIC(8,2),
    CONSTRAINT chk_route_distance CHECK (distance_km IS NULL OR distance_km > 0)
);

-- 15. Довідник статусів доставки
CREATE TABLE delivery_status (
    status_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_name VARCHAR(50) NOT NULL UNIQUE
);

-- 16. Доставки (1:1 з набором допомоги)
--     volunteer_note додано в ЛР №6
CREATE TABLE delivery (
    delivery_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kit_id         INTEGER NOT NULL UNIQUE,
    volunteer_id   INTEGER NOT NULL,
    route_id       INTEGER NOT NULL,
    status_id      INTEGER NOT NULL DEFAULT 1,
    planned_date   DATE    NOT NULL,
    actual_date    DATE,
    volunteer_note VARCHAR(500),
    CONSTRAINT fk_delivery_kit       FOREIGN KEY (kit_id)       REFERENCES aid_kit (kit_id),
    CONSTRAINT fk_delivery_volunteer FOREIGN KEY (volunteer_id) REFERENCES volunteer (volunteer_id),
    CONSTRAINT fk_delivery_route     FOREIGN KEY (route_id)     REFERENCES route (route_id),
    CONSTRAINT fk_delivery_status    FOREIGN KEY (status_id)    REFERENCES delivery_status (status_id)
);

-- 17. Відгуки отримувачів (ЛР №6): feedback -> requester (N:1), feedback -> delivery (1:1)
CREATE TABLE feedback (
    feedback_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id INTEGER      NOT NULL,
    delivery_id  INTEGER      NOT NULL UNIQUE,
    rating       SMALLINT     NOT NULL,
    review_text  VARCHAR(1000),
    created_at   DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT fk_feedback_requester FOREIGN KEY (requester_id)
        REFERENCES requester (requester_id),
    CONSTRAINT fk_feedback_delivery FOREIGN KEY (delivery_id)
        REFERENCES delivery (delivery_id),
    CONSTRAINT chk_feedback_rating CHECK (rating BETWEEN 1 AND 5)
);

-- Індекси на зовнішніх ключах, які сайт використовує найчастіше
CREATE INDEX idx_help_request_requester ON help_request (requester_id);
CREATE INDEX idx_help_request_state     ON help_request (request_state);
CREATE INDEX idx_aid_kit_request        ON aid_kit (request_id);
CREATE INDEX idx_delivery_status        ON delivery (status_id);
CREATE INDEX idx_delivery_volunteer     ON delivery (volunteer_id);
CREATE INDEX idx_donation_donor         ON donation (donor_id);
