-- Залишки: кожен новий товар (без жодного рядка в stock) лежить на трьох складах із п'яти
INSERT INTO stock (warehouse_id, item_id, quantity)
SELECT w.warehouse_id, i.item_id, 30 + ((i.item_id * 7 + w.warehouse_id * 13) % 170)
FROM item i
CROSS JOIN warehouse w
WHERE NOT EXISTS (SELECT 1 FROM stock s WHERE s.item_id = i.item_id)
  AND (i.item_id + w.warehouse_id) % 5 < 3
ON CONFLICT (warehouse_id, item_id) DO NOTHING;

